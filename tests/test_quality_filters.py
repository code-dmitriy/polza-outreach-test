"""Фильтры качества на настоящих строках из прогонов.

Каждый пример ниже реально попал в базу и был бы отправлен клиенту.
Вторая половина — обратная проверка: нормальные описания должны выживать.
"""

import pytest

from src.personalize import build
from src.site_facts import CompanyFacts


def _p(text):
    return build("Компания", CompanyFacts(
        domain="x.ru", reachable=True, pages_seen=["https://x.ru"],
        description=text, description_source="https://x.ru"))


@pytest.mark.parametrize("text", [
    # текст вообще не про эту компанию — документация хостера
    'Что это значит и как прилинковать домен? "Линковка" - это направление '
    'домена на директорию на сервере, которая становится доступна в интернете.',
    # шаблонная рыба, оставшаяся от чужого сайта: у конного завода — про банк
    "Обратитесь к нашим специалистам и получите профессиональную консультацию "
    "по услугам нашего банка.",
    # заглушка вместо описания
    "Мы работаем над улучшением нашего сайта, чтобы сделать его ещё удобнее.",
    # объявление, которое протухнет
    'АО СМФ "Верола уходит в ежегодный корпоративный отпуск с 01 июля 2026 года.',
    "Коллеги и друзья, отметьте в своих календарях даты с 19 по 21 марта 2024 года.",
    # виджет карты и телефоны
    "Производственная, Уч.№1 Проложить маршрут Телефон 8 (495) 221-38-78 завод.",
    "Завод производит металлочерепицу и профлист. 8 800 2222 507 офис продаж.",
    # имена файлов картинок, утёкшие в текст страницы
    "Производитель продуктов из пшеницы. 1920_668 agrofirma-meschovskaya 2 колос.",
    # счётчик, который подгружается скриптом: в HTML остаётся ноль
    "Официальный сайт Южной Соковой Компании. 0 тонн яблок перерабатывается в сутки.",
    # почтовый адрес вместо описания
    "Производство профилей на заказ. Ижевск, Воткинское шоссе, д. 298 Склад корпус 1.",
])
def test_junk_never_reaches_the_letter(text):
    assert not _p(text).usable


@pytest.mark.parametrize("text", [
    "Фабрика сетей Люксол — производство капроновых и полипропиленовых сеток и шнуров.",
    "Комбинат Алтайтара — производство гофрокартона. Компания создана в 2007 году в Барнауле.",
    "Предприятие основано в 1967 году для воспроизводства радужной форели, деликатесной рыбы.",
    "С 2008 года и по настоящий день группа компаний ЧСЗ по праву считается крупнейшей в России.",
    "Дмитровский завод гибкой упаковки – производитель упаковки из полимерных материалов с 1979 года.",
])
def test_real_descriptions_survive(text):
    assert _p(text).usable


def test_leading_numbers_are_cut_not_the_whole_line():
    """«2022 2015 Завод занимает…» — подписи под годами в ленте достижений."""
    p = _p("2022 2015 Завод занимает лидирующее положение на рынке горнорудных долот России.")
    assert p.usable and p.text.startswith("Завод занимает")


def test_shouting_header_is_calmed_not_removed():
    """Срезать капслок нельзя: останется «Заключается в…» без подлежащего."""
    p = _p("МИССИЯ КОМПАНИИ заключается в удовлетворении потребностей "
           "производителей товарной свинины.")
    assert p.usable and p.text.startswith("Миссия компании заключается")


def test_self_sufficient_first_sentence_is_enough():
    """Второе предложение на сайтах сплошь и рядом про другое: у гипсового
    комбината следом шло «наш интернет-магазин одним из первых начал on-line
    продажу одежды». Если первое самодостаточно, второе не берём."""
    p = _p("Самарский гипсовый комбинат - одно из крупнейших предприятий "
           "гипсовой отрасли России. Наша компания была основана в 1993 году, "
           "а наш интернет-магазин стал одним из первых магазинов, "
           "осуществляющих on-line продажу одежды в регионе.")
    assert p.usable
    assert "одежды" not in p.text
    assert p.text.startswith("Самарский гипсовый комбинат")


def test_short_first_sentence_still_gets_a_second():
    p = _p("Комбинат Алтайтара — производство гофротары. "
           "Компания создана в 2007 году в Барнауле, столице Алтайского края.")
    assert p.usable and "2007" in p.text


def test_parked_domain_page_is_rejected():
    """Сайт не работает, домен запаркован — весь лид фиктивный."""
    assert not _p('Если домен никуда не направлен, Вы видите данную страницу. '
                  'Если Вы владелец домена - прилинкуйте домен в разделе "Сайты".').usable


def test_block_headings_without_a_single_full_stop_are_menu():
    assert not _p("Научные исследования и разработки Производство, программирование "
                  "и внедрение Гарантийное обслуживание Поставка сервисной аппаратуры").usable


def test_run_of_capitalised_words_is_a_city_list():
    assert not _p("Производство упаковки в Москве. Кривцово Санкт-Петербург Краснодар "
                  "Производство упаковки из гофрокартона с 1999 года").usable


def test_boilerplate_shared_between_unrelated_sites_is_rejected():
    """Эта фраза слово в слово стоит и у гипсового комбината, и у трикотажной
    фабрики — типовой текст шаблона, а не факт о компании."""
    assert not _p("Наша компания была основана в 1993 году, а наш интернет-магазин "
                  "стал одним из первых магазинов, осуществляющих on-line продажу "
                  "одежды в регионе.").usable


def test_second_sentence_repeating_the_first_is_dropped():
    p = _p("Одна из старейших компаний по открытой добыче каменного угля в России. "
           "«Кузбассразрезуголь» — одна из старейших компаний в сфере добычи угля.")
    assert p.usable
    assert p.text.count("старейших") == 1
